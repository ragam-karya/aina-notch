"""
Adds the soft "jelly" body deformation to components/body.rml (Phase 6 polish).

- Gives the six silhouette vertices of Rim and Body Base stable ids, and keys
  both outlines identically so the rim always hugs the body.
- Each vertex drifts on a slow sine (own phase) and its handles breathe, so the
  droplet outline gently morphs instead of only scaling.
- The watercolor washes drift and the sheen shimmers, which reads as liquid.

One seamless 4 s loop on the Body SM's "Jelly" layer. Idempotent: rerun after
editing the numbers. Run from the project root: python tools/gen_body_jelly.py
"""
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
P = ROOT / "components/body.rml"

DUR = 240                     # frames (4 s at 60 fps)
STEPS = 8                     # keys per loop (every 30 frames), eased between
RIM_IDS = [f"0:{1061 + i}" for i in range(6)]
BASE_IDS = [f"0:{1071 + i}" for i in range(6)]
LAYER_ID, STATE_ID, ANIM_ID = "0:1092", "0:1093", "0:1094"

# Base silhouette: (x, y, rotation, distance), and per-vertex wobble (ampX, ampY, ampDist, phase).
VERTS = [(20, -122, 0.08, 44), (106, -28, 1.3, 50), (84, 84, 2.35, 44),
         (-14, 112, 3.1416, 62), (-114, 36, -1.6, 52), (-78, -64, -0.82, 50)]
WOBBLE = [(2.5, 3.5, 4, 0.0), (3.5, 2.5, 4, 1.1), (3, 3, 3, 2.3),
          (2.5, 2.5, 5, 3.4), (3.5, 2.5, 4, 4.4), (3, 3, 4, 5.4)]
# Washes: id -> (base x, base y, ampX, ampY, phase)
WASHES = {"0:1031": (-8, -8, 5, 4, 0.0), "0:1032": (-60, -56, 4, 3, 1.4), "0:1033": (58, -58, 6, 5, 2.6),
          "0:1034": (72, 40, 5, 6, 3.9), "0:1035": (-66, 72, 7, 4, 5.0), "0:1036": (10, 96, 6, 3, 0.8)}
SHEEN = "0:1013"
EASE = '<CubicEaseInterpolator x1="0.42" y1="0" x2="0.58" y2="1"/>'


def f(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def wave(base, amp, phase):
    keys = []
    for i in range(STEPS + 1):
        t = i / STEPS
        keys.append((round(t * DUR), base + amp * math.sin(2 * math.pi * t + phase)))
    keys[-1] = (DUR, keys[0][1])   # exact seam
    return keys


def track(obj, prop, keys, ind="            "):
    out = [f'{ind}<KeyedProperty property="{prop}">\n']
    for n, (fr, v) in enumerate(keys):
        if n == len(keys) - 1:
            out.append(f'{ind}    <KeyFrameDouble value="{f(v)}" frame="{fr}"/>\n')
        else:
            out.append(f'{ind}    <KeyFrameDouble value="{f(v)}" frame="{fr}" interpolationType="cubic">{EASE}</KeyFrameDouble>\n')
    out.append(f'{ind}</KeyedProperty>\n')
    return "".join(out)


def keyed(obj, tracks):
    return f'        <KeyedObject objectId="{obj}">\n' + "".join(tracks) + '        </KeyedObject>\n'


def build_anim():
    objs = []
    for ids in (RIM_IDS, BASE_IDS):
        for vid, (x, y, _r, d), (ax, ay, ad, ph) in zip(ids, VERTS, WOBBLE):
            objs.append(keyed(vid, [track(vid, "x", wave(x, ax, ph)),
                                    track(vid, "y", wave(y, ay, ph + 1.3)),
                                    track(vid, "distance", wave(d, ad, ph + 0.6))]))
    for wid, (x, y, ax, ay, ph) in WASHES.items():
        objs.append(keyed(wid, [track(wid, "x", wave(x, ax, ph)), track(wid, "y", wave(y, ay, ph + 1.7))]))
    objs.append(keyed(SHEEN, [track(SHEEN, "opacity", wave(0.9, 0.1, 0.5))]))
    return (f'        <!-- @gen:jelly -->\n'
            f'        <!-- Jelly: the outline gently morphs, washes drift, sheen shimmers. Generated by tools/gen_body_jelly.py -->\n'
            f'        <LinearAnimation loopValue="loop" duration="{DUR}" name="Jelly" id="{ANIM_ID}">\n'
            + "".join(objs) +
            f'        </LinearAnimation>\n'
            f'        <!-- @end:jelly -->\n')


def main():
    s = P.read_text(encoding="utf-8")

    # Stable ids on the silhouette vertices (Rim path 0:1021, Body Base path 0:1041).
    for path_id, ids in (("0:1021", RIM_IDS), ("0:1041", BASE_IDS)):
        m = re.search(r'(<PointsPath[^>]*id="%s">)(.*?)(</PointsPath>)' % path_id, s, flags=re.S)
        body = m.group(2)
        verts = re.findall(r'<CubicMirroredVertex[^>]*/>', body)
        assert len(verts) == 6, (path_id, len(verts))
        new = body
        for v, vid in zip(verts, ids):
            nv = re.sub(r' id="[^"]*"', "", v).replace("/>", f' id="{vid}"/>')
            new = new.replace(v, nv, 1)
        s = s[:m.start(2)] + new + s[m.end(2):]

    # State machine: Entry -> Jelly (looping).
    sm = (f'        <StateMachine name="Body SM" id="0:1090">\n'
          f'            <StateMachineLayer name="Jelly" id="0:1091">\n'
          f'                <AnyState x="400" y="0"/>\n'
          f'                <ExitState x="560" y="0"/>\n'
          f'                <EntryState x="0" y="0">\n'
          f'                    <StateTransition stateToId="{STATE_ID}"/>\n'
          f'                </EntryState>\n'
          f'                <AnimationState x="200" y="0" animationId="{ANIM_ID}" id="{STATE_ID}"/>\n'
          f'            </StateMachineLayer>\n'
          f'        </StateMachine>\n')
    s = re.sub(r'        <StateMachine name="Body SM".*?</StateMachine>\n', lambda m: sm, s, flags=re.S)

    block = build_anim()
    if "<!-- @gen:jelly -->" in s:
        s = re.sub(r"        <!-- @gen:jelly -->.*?<!-- @end:jelly -->\n", lambda m: block, s, flags=re.S)
    else:
        s = s.replace("    </Artboard>\n\n    <ComponentAsset artboardId=\"0:1000\"",
                      block + "    </Artboard>\n\n    <ComponentAsset artboardId=\"0:1000\"", 1)
    P.write_text(s, encoding="utf-8")
    print("body jelly generated")


if __name__ == "__main__":
    main()
